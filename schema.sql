CREATE TABLE IF NOT EXISTS contacts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 surname VARCHAR(100) NOT NULL, first_name VARCHAR(100) NOT NULL,
 patronymic VARCHAR(100) NOT NULL DEFAULT '', gender VARCHAR(12) NOT NULL DEFAULT '',
 birth_date DATE NULL, phone VARCHAR(40) NOT NULL DEFAULT '',
 address VARCHAR(300) NOT NULL DEFAULT '', email VARCHAR(254) NOT NULL DEFAULT '', comment TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
